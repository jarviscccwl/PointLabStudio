"""Layout-only construction for the recording workspace.

The host owns source state and callbacks. Keeping the chrome here makes the
navigation/decoding controller independent of toolbar and settings arrangement.
"""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QComboBox, QDialog, QDialogButtonBox, QDoubleSpinBox, QFrame, QGridLayout, QHBoxLayout, QLabel,
    QMenu, QSlider, QSpinBox, QSplitter, QTabWidget, QToolButton, QVBoxLayout,
    QWidget, QSizePolicy,
)

from ui.theme import get_theme
from ui.widgets.data_view import DataView, ElidedLabel
from ui.widgets.calibration_controls import CalibrationPanel


def tool_button(text, tooltip="", checkable=False):
    button = QToolButton()
    button.setText(text)
    button.setToolTip(tooltip or text)
    button.setCheckable(checkable)
    button.setFocusPolicy(Qt.StrongFocus)
    button.setAccessibleName(tooltip or text)
    return button


def stream_combo():
    combo = QComboBox()
    combo.setMinimumWidth(120)
    combo.setMinimumContentsLength(12)
    combo.setSizeAdjustPolicy(QComboBox.AdjustToMinimumContentsLengthWithIcon)
    combo.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Fixed)
    combo.view().setTextElideMode(Qt.ElideMiddle)
    return combo


class RecordingChromeMixin:
    def _build_chrome(self, theme, viewport_factory):
        self.setObjectName("recordingBrowser")
        self.setAttribute(Qt.WA_StyledBackground)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(8)
        self.toolbar = QFrame()
        self.toolbar.setObjectName("recordingToolbar")
        toolbar_layout = QVBoxLayout(self.toolbar)
        toolbar_layout.setContentsMargins(8, 6, 8, 6)
        row = QHBoxLayout()
        toolbar_layout.addLayout(row)
        row.setContentsMargins(8, 6, 8, 6)
        row.setSpacing(6)
        self.primary = stream_combo()
        self.primary.setToolTip("主视图 · 也可在左侧场景中选择话题")
        self.compare = tool_button("同步查看", "将另一条数据流与主视图按时间匹配", True)
        self.swap_button = tool_button("⇄", "交换主视图与对照视图")
        self.secondary = stream_combo()
        self.secondary.setToolTip("对照视图 · 按主视图的时间寻找最接近的帧")
        self.settings_button = tool_button("浏览设置", "时间匹配、相机参数与投影设置", True)
        self.more_button = tool_button("更多", "数据源、导出和处理操作")
        menu = QMenu(self.more_button)
        self.options_action = menu.addAction("数据包概览 / 重新选择…")
        self.reload_action = menu.addAction("重新读取数据源")
        menu.addSeparator()
        self.scene_button = menu.addAction("当前点云加入场景")
        self.more_button.setMenu(menu)
        self.more_button.setPopupMode(QToolButton.InstantPopup)
        row.addWidget(self.primary, 1)
        row.addWidget(self.compare)
        row.addWidget(self.settings_button)
        row.addWidget(self.more_button)
        self.comparison_row = QWidget()
        comparison = QHBoxLayout(self.comparison_row)
        comparison.setContentsMargins(0, 0, 0, 0)
        comparison.addWidget(QLabel("对照"))
        comparison.addWidget(self.secondary, 1)
        comparison.addWidget(self.swap_button)
        toolbar_layout.addWidget(self.comparison_row)
        layout.addWidget(self.toolbar)

        self.settings_panel = QDialog(self, Qt.Tool)
        self.settings_panel.setWindowTitle("浏览设置")
        self.settings_panel.resize(600, 380)
        settings_layout = QVBoxLayout(self.settings_panel)
        self.settings_tabs = QTabWidget()
        self.settings_tabs.setObjectName("recordingSettings")
        settings_layout.addWidget(self.settings_tabs)
        self.sync_panel = QWidget()
        settings = QGridLayout(self.sync_panel)
        settings.setContentsMargins(12, 10, 12, 10)
        settings.setHorizontalSpacing(12)
        settings.setVerticalSpacing(8)
        self.basis = QComboBox()
        self.basis.addItem("记录 / 抓包时间", "record")
        self.basis.addItem("设备 / 消息头时间", "device")
        self.tolerance = QDoubleSpinBox()
        self.tolerance.setRange(0, 100_000)
        self.tolerance.setValue(50)
        self.tolerance.setDecimals(3)
        self.tolerance.setKeyboardTracking(False)
        self.tolerance.setSuffix(" ms")
        self.tolerance.setMaximumWidth(155)
        self.offset = QDoubleSpinBox()
        self.offset.setRange(-100_000_000, 100_000_000)
        self.offset.setDecimals(3)
        self.offset.setKeyboardTracking(False)
        self.offset.setSuffix(" ms")
        self.offset.setMaximumWidth(180)
        self.offset.setToolTip("偏移加在对照数据流时间上；正值表示将对照时间向后移")
        self.reset_offset = tool_button("清零", "清除对照时间偏移")
        self.reset_offset.clicked.connect(lambda: self.offset.setValue(0))
        settings.addWidget(QLabel("时间基准"), 0, 0)
        settings.addWidget(self.basis, 0, 1)
        settings.addWidget(QLabel("匹配容差"), 1, 0)
        settings.addWidget(self.tolerance, 1, 1)
        settings.addWidget(QLabel("对照时间偏移"), 2, 0)
        settings.addWidget(self.offset, 2, 1)
        settings.addWidget(self.reset_offset, 2, 2, Qt.AlignLeft)
        self.sync_hint = QLabel("仅匹配容差内最近的帧。缺少所选时间时不会猜测；偏移不会修改原始文件。")
        self.sync_hint.setWordWrap(True)
        self.sync_hint.setObjectName("dim")
        settings.addWidget(self.sync_hint, 3, 0, 1, 3)
        settings.setRowStretch(4, 1)
        settings.setColumnStretch(1, 1)
        self.settings_tabs.addTab(self.sync_panel, "时间匹配")
        self.calibration_panel = CalibrationPanel()
        for name in ("camera", "calibration_button", "undistort", "overlay", "calibration_label"):
            setattr(self, name, getattr(self.calibration_panel, name))
        self.settings_tabs.addTab(self.calibration_panel, "相机与投影")
        close_settings = QDialogButtonBox(QDialogButtonBox.Close)
        close_settings.button(QDialogButtonBox.Close).setText("关闭")
        close_settings.rejected.connect(self.settings_panel.reject)
        settings_layout.addWidget(close_settings)
        self.settings_panel.hide()
        self.settings_button.toggled.connect(self.settings_panel.setVisible)
        self.settings_panel.finished.connect(lambda: self.settings_button.setChecked(False))

        self.panes = QSplitter(Qt.Horizontal)
        self.panes.setChildrenCollapsible(False)
        self.panes.setHandleWidth(6)
        self.left = DataView(theme, viewport_factory)
        self.right = DataView(theme, viewport_factory)
        self.panes.addWidget(self.left)
        self.panes.addWidget(self.right)
        self.panes.setStretchFactor(0, 1)
        self.panes.setStretchFactor(1, 1)
        self.right.hide()
        layout.addWidget(self.panes, 1)

        self.transport = QFrame()
        self.transport.setObjectName("recordingTransport")
        bottom = QVBoxLayout(self.transport)
        bottom.setContentsMargins(10, 8, 10, 7)
        bottom.setSpacing(5)
        self.slider = QSlider(Qt.Horizontal)
        self.slider.setTracking(False)
        self.slider.setToolTip("拖动选择帧，松手后读取；也可输入帧号或按时间定位")
        bottom.addWidget(self.slider)
        navigation = QHBoxLayout()
        navigation.setSpacing(6)
        self.previous = tool_button("‹", "上一帧（←）")
        self.play = tool_button("播放", "按指定帧率播放，单帧读取完成后继续", True)
        self.next = tool_button("›", "下一帧（→）")
        self.previous.setMinimumWidth(28)
        self.next.setMinimumWidth(28)
        self.position = QSpinBox()
        self.position.setRange(1, 1)
        self.position.setMinimumWidth(64)
        self.position.setMaximumWidth(90)
        self.position.setKeyboardTracking(False)
        self.position.setToolTip("当前选中范围内的帧序号，从 1 开始")
        self.total = QLabel("/ 0")
        self.total.setObjectName("dim")
        self.rate = QDoubleSpinBox()
        self.rate.setRange(0.1, 120)
        self.rate.setValue(10)
        self.rate.setDecimals(1)
        self.rate.setSuffix(" 帧/秒")
        self.rate.setMaximumWidth(110)
        self.time_label = ElidedLabel()
        self.time_label.setObjectName("dim")
        self.jump_button = tool_button("时间定位", "跳到相对于当前数据流起点的时间")
        self.export_button = tool_button("导出", "导出当前主视图；菜单中可选择对照视图")
        export_menu = QMenu(self.export_button)
        self.export_primary_action = export_menu.addAction("导出主视图当前内容…")
        self.export_secondary_action = export_menu.addAction("导出对照视图当前内容…")
        self.export_button.setMenu(export_menu)
        self.export_button.setPopupMode(QToolButton.MenuButtonPopup)
        for widget in (self.previous, self.play, self.next, self.position, self.total, self.rate):
            navigation.addWidget(widget)
        navigation.addWidget(self.time_label, 1)
        navigation.addWidget(self.jump_button)
        navigation.addWidget(self.export_button)
        bottom.addLayout(navigation)
        self.status = ElidedLabel()
        self.status.setTextInteractionFlags(Qt.TextSelectableByMouse)
        self.status.setObjectName("dim")
        status_policy = self.status.sizePolicy()
        status_policy.setRetainSizeWhenHidden(True)
        self.status.setSizePolicy(status_policy)
        self.status.hide()
        bottom.addWidget(self.status)
        layout.addWidget(self.transport)
        self._style_chrome(theme)

    def _style_chrome(self, theme):
        colors = get_theme(theme)
        self.setStyleSheet(f"""
            QWidget#recordingBrowser {{ background: {colors['bg']}; }}
            QFrame#recordingToolbar, QFrame#recordingTransport {{
                background: {colors['panel']}; border: 1px solid {colors['border']}; border-radius: 9px;
            }}
            QTabWidget#recordingSettings::pane {{
                background: {colors['panel']}; border: 1px solid {colors['border']}; border-radius: 7px;
            }}
        """)
        self.calibration_panel.set_theme(theme)
